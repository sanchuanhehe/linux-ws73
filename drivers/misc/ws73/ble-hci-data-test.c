/* Synthetic controller model ONLY for KUnit, never a USB firmware fallback. */
#include <kunit/test.h>
#include <linux/completion.h>
#include <linux/delay.h>
#include <linux/device.h>
#include <linux/err.h>
#include <linux/jiffies.h>
#include <linux/kthread.h>
#include <linux/sched.h>
#include <linux/sched/task.h>
#include <linux/unaligned.h>
#include <net/bluetooth/bluetooth.h>
#include <net/bluetooth/hci_core.h>

#include "ble.h"

struct ws73_hci_model {
	struct device *parent;
	struct auxiliary_device *adev;
	struct hci_dev *hdev; /* Held device reference, separate from the driver. */
	struct completion published;
	struct completion reset;
	struct completion release;
	struct completion acl;
	struct completion flushing;
	struct completion flushed;
	struct task_struct *flusher;
	int flush_result;
	bool block;
	unsigned int commands;
	unsigned int acls;
	int wire_error;
};

static const u8 ws73_model_address[] = { 0xc0, 0xde, 0x73, 0, 0, 2 };
static const u8 ws73_model_acl[] = { 1, 0, 3, 0, 0xaa, 0xbb, 0xcc };
static const u8 ws73_model_record[] = {
	0, 7, 8, 0, 2, 1, 0, 3, 0, 0xaa, 0xbb, 0xcc, 0, 0, 0, 0,
};

static int ws73_model_action(void *context, bool enabled)
{
	/* Synthetic action acknowledgment; it says nothing about real USB. */
	return 0;
}

static int ws73_model_send(void *context, const u8 *data, size_t length)
{
	struct ws73_hci_model *m = context;
	u8 reply[15] = { HCI_EVENT_PKT, HCI_EV_CMD_COMPLETE, 0, 1 };
	u16 opcode;
	size_t size;

	if (!wait_for_completion_timeout(&m->published, 5 * HZ))
		return -ETIMEDOUT;
	if (length == sizeof(ws73_model_record) &&
	    !memcmp(data, ws73_model_record, length)) {
		m->acls++;
		complete(&m->acl);
		return 0;
	}
	if (length != 8 || data[0] || data[1] != 7 || data[2] != 4 ||
	    data[3] || data[4] != HCI_COMMAND_PKT || data[7])
		goto invalid;
	opcode = get_unaligned_le16(data + 5);
	m->commands++;
	if (opcode == HCI_OP_RESET && m->commands == 3) {
		/* Park AFTER the real driver's two setup queries, before full init. */
		complete(&m->reset);
		if (m->block && !wait_for_completion_timeout(&m->release, 5 * HZ))
			return -ETIMEDOUT;
		return 0;
	}
	put_unaligned_le16(opcode, reply + 4);
	if (opcode == HCI_OP_READ_LOCAL_FEATURES && m->commands == 1) {
		reply[11] = LMP_LE | LMP_NO_BREDR;
		size = 15;
	} else if (opcode == HCI_OP_READ_BD_ADDR && m->commands == 2) {
		memcpy(reply + 7, ws73_model_address, sizeof(ws73_model_address));
		size = 13;
	} else {
		goto invalid;
	}
	reply[2] = size - 3;
	/* Test-model events, including ncmd, are not generated by the driver. */
	ws73_ble_receive(m->adev, reply, 1);
	ws73_ble_receive(m->adev, reply + 1, 2);
	ws73_ble_receive(m->adev, reply + 3, size - 3);
	return 0;
invalid:
	m->wire_error = -EPROTO;
	return -EPROTO;
}

static const struct ws73_ble_backend ws73_model_backend = {
	.set_enabled = ws73_model_action,
	.send = ws73_model_send,
};

static void ws73_model_cleanup(void *context)
{
	struct ws73_hci_model *m = context;

	if (m->adev)
		ws73_ble_fault(m->adev, -ECANCELED);
	complete_all(&m->published);
	complete_all(&m->release);
	if (m->flusher) {
		kthread_stop(m->flusher);
		put_task_struct(m->flusher);
	}
	if (m->adev) {
		/* Join the synchronous model call before dropping its context. */
		ws73_ble_stop(m->adev);
		ws73_ble_remove(m->adev);
	}
	if (m->hdev)
		hci_dev_put(m->hdev);
	if (m->parent)
		root_device_unregister(m->parent);
}

static int ws73_model_match(struct device *dev, const void *unused)
{
	return dev->class && !strcmp(dev->class->name, "bluetooth") &&
	       dev->type && !strcmp(dev->type->name, "host");
}

static struct ws73_hci_model *ws73_model_create(struct kunit *test, bool block)
{
	struct ws73_hci_model *m;
	struct device *child;

	m = kunit_kzalloc(test, sizeof(*m), GFP_KERNEL);
	if (!m)
		return NULL;
	init_completion(&m->published);
	init_completion(&m->reset);
	init_completion(&m->release);
	init_completion(&m->acl);
	init_completion(&m->flushing);
	init_completion(&m->flushed);
	m->block = block;
	if (kunit_add_action_or_reset(test, ws73_model_cleanup, m))
		return NULL;
	m->parent = root_device_register(test->name);
	if (IS_ERR(m->parent)) {
		m->parent = NULL;
		return NULL;
	}
	m->adev = ws73_ble_add(m->parent, &ws73_model_backend, m);
	if (IS_ERR(m->adev)) {
		m->adev = NULL;
		return NULL;
	}
	complete_all(&m->published);
	if (!wait_for_completion_timeout(&m->reset, 5 * HZ))
		return NULL;
	child = device_find_child(&m->adev->dev, NULL, ws73_model_match);
	if (!child)
		return NULL;
	m->hdev = to_hci_dev(child);
	return m;
}

static struct sk_buff *ws73_model_packet(void)
{
	struct sk_buff *skb = bt_skb_alloc(sizeof(ws73_model_acl), GFP_KERNEL);

	if (skb) {
		skb_put_data(skb, ws73_model_acl, sizeof(ws73_model_acl));
		hci_skb_pkt_type(skb) = HCI_ACLDATA_PKT;
	}
	return skb;
}

static int ws73_model_count(struct device *dev, void *context)
{
	unsigned int *count = context;

	(*count)++;
	return 0;
}

static void ws73_model_withdrawn(struct kunit *test, struct ws73_hci_model *m)
{
	unsigned long deadline = jiffies + 5 * HZ;
	unsigned int children;

	do {
		children = 0;
		device_for_each_child(&m->adev->dev, &children, ws73_model_count);
		if (!children)
			break;
		msleep(20);
	} while (time_before(jiffies, deadline));
	KUNIT_EXPECT_EQ(test, children, 0);
	KUNIT_EXPECT_EQ(test, m->wire_error, 0);
}

static void ws73_hci_data_test(struct kunit *test)
{
	struct ws73_hci_model *m = ws73_model_create(test, false);
	const u8 expected[] = { 0xff, 3, 0x41, 0x42, 0x43 };
	u8 event[] = { HCI_EVENT_PKT, 0xff, 3, 0x41, 0x42, 0x43 };
	struct sk_buff *skb, *received;
	unsigned long flags;
	unsigned int before;
	int ret;

	KUNIT_ASSERT_NOT_NULL(test, m);
	KUNIT_EXPECT_EQ(test, m->commands, 3);
	KUNIT_EXPECT_MEMEQ(test, &m->hdev->bdaddr, ws73_model_address, 6);
	skb = ws73_model_packet();
	KUNIT_ASSERT_NOT_NULL(test, skb);
	ret = m->hdev->send(m->hdev, skb);
	if (ret)
		kfree_skb(skb);
	KUNIT_ASSERT_EQ(test, ret, 0);
	KUNIT_ASSERT_TRUE(test, wait_for_completion_timeout(&m->acl, HZ));
	/* Empty flush joins TX; RX must remain enabled afterward. */
	KUNIT_ASSERT_EQ(test, m->hdev->flush(m->hdev), 0);
	KUNIT_EXPECT_EQ(test, m->acls, 1);
	KUNIT_EXPECT_EQ(test, m->hdev->stat.acl_tx, 1);

	/* Hold stack processing to inspect ownership after the borrowed input changes. */
	disable_work_sync(&m->hdev->rx_work);
	before = m->hdev->stat.byte_rx;
	ws73_ble_receive(m->adev, event, 2);
	KUNIT_EXPECT_EQ(test, m->hdev->stat.byte_rx, before);
	event[0] = 0;
	event[1] = 0;
	ws73_ble_receive(m->adev, event + 2, sizeof(event) - 2);
	memset(event, 0xee, sizeof(event));
	spin_lock_irqsave(&m->hdev->rx_q.lock, flags);
	received = skb_peek(&m->hdev->rx_q);
	if (received)
		skb_get(received);
	spin_unlock_irqrestore(&m->hdev->rx_q.lock, flags);
	KUNIT_EXPECT_NOT_NULL(test, received);
	if (received) {
		KUNIT_EXPECT_EQ(test, hci_skb_pkt_type(received), HCI_EVENT_PKT);
		KUNIT_EXPECT_EQ(test, received->len, sizeof(expected));
		if (received->len == sizeof(expected))
			KUNIT_EXPECT_MEMEQ(test, received->data, expected, sizeof(expected));
		kfree_skb(received);
	}
	enable_work(&m->hdev->rx_work);
	queue_work(m->hdev->workqueue, &m->hdev->rx_work);
	flush_work(&m->hdev->rx_work);
	KUNIT_EXPECT_EQ(test, m->hdev->stat.byte_rx, before + sizeof(expected));
	ws73_ble_fault(m->adev, -ECANCELED);
	/* Cancellation wakes the parked real HCI request, without a Reset reply. */
	ws73_model_withdrawn(test, m);
}

static void ws73_hci_queue_limit_test(struct kunit *test)
{
	struct ws73_hci_model *m = ws73_model_create(test, true);
	struct sk_buff *skb;
	unsigned int i;
	int ret;

	KUNIT_ASSERT_NOT_NULL(test, m);
	/* The blocked Reset owns one slot; exactly 63 further packets fit. */
	for (i = 0; i < 63; i++) {
		skb = ws73_model_packet();
		KUNIT_ASSERT_NOT_NULL(test, skb);
		ret = m->hdev->send(m->hdev, skb);
		if (ret)
			kfree_skb(skb);
		KUNIT_ASSERT_EQ(test, ret, 0);
	}
	skb = ws73_model_packet();
	KUNIT_ASSERT_NOT_NULL(test, skb);
	KUNIT_EXPECT_EQ(test, m->hdev->send(m->hdev, skb), -ENOBUFS);
	KUNIT_EXPECT_MEMEQ(test, skb->data, ws73_model_acl, sizeof(ws73_model_acl));
	KUNIT_EXPECT_EQ(test, m->hdev->send(m->hdev, skb), -ENOBUFS);
	kfree_skb(skb);
	complete_all(&m->release);
	ws73_model_withdrawn(test, m);
	KUNIT_EXPECT_EQ(test, m->acls, 0);
	KUNIT_EXPECT_EQ(test, ws73_ble_start(m->adev), -ENOBUFS);
}

static void ws73_hci_byte_limit_test(struct kunit *test)
{
	struct ws73_hci_model *m = ws73_model_create(test, true);
	struct sk_buff *skb;
	unsigned int i;
	int ret;

	KUNIT_ASSERT_NOT_NULL(test, m);
	/* 43 maximum H4 packets plus the 4-byte Reset fit in 64 KiB. */
	for (i = 0; i < 44; i++) {
		skb = bt_skb_alloc(BTWS73_H4_MAX_SIZE - 1, GFP_KERNEL);
		KUNIT_ASSERT_NOT_NULL(test, skb);
		skb_put_zero(skb, BTWS73_H4_MAX_SIZE - 1);
		put_unaligned_le16(1, skb->data);
		put_unaligned_le16(BTWS73_H4_MAX_SIZE - 5, skb->data + 2);
		hci_skb_pkt_type(skb) = HCI_ACLDATA_PKT;
		ret = m->hdev->send(m->hdev, skb);
		if (ret)
			kfree_skb(skb);
		KUNIT_ASSERT_EQ(test, ret, i < 43 ? 0 : -ENOBUFS);
	}
	complete_all(&m->release);
	ws73_model_withdrawn(test, m);
	KUNIT_EXPECT_EQ(test, m->acls, 0);
	KUNIT_EXPECT_EQ(test, ws73_ble_start(m->adev), -ENOBUFS);
}

static void ws73_hci_rejected_acl_test(struct kunit *test)
{
	struct ws73_hci_model *m = ws73_model_create(test, false);
	struct sk_buff *skb;

	KUNIT_ASSERT_NOT_NULL(test, m);
	skb = ws73_model_packet();
	KUNIT_ASSERT_NOT_NULL(test, skb);
	put_unaligned_le16(4, skb->data + 2); /* Actual payload is only three. */
	KUNIT_EXPECT_EQ(test, m->hdev->send(m->hdev, skb), -EMSGSIZE);
	KUNIT_EXPECT_EQ(test, skb->len, sizeof(ws73_model_acl));
	kfree_skb(skb);
	ws73_model_withdrawn(test, m);
	KUNIT_EXPECT_EQ(test, m->acls, 0);
	KUNIT_EXPECT_EQ(test, ws73_ble_start(m->adev), -EMSGSIZE);
}

/* Capture the owned RX queue while native processing is deliberately stopped. */
static void ws73_model_expect_rx(struct kunit *test, struct ws73_hci_model *m,
				 const u8 *h4, size_t size)
{
	struct sk_buff *skb = skb_dequeue(&m->hdev->rx_q);

	KUNIT_EXPECT_NOT_NULL(test, skb);
	if (!skb)
		return;
	KUNIT_EXPECT_EQ(test, hci_skb_pkt_type(skb), h4[0]);
	KUNIT_EXPECT_EQ(test, skb->len, size - 1);
	if (skb->len == size - 1)
		KUNIT_EXPECT_MEMEQ(test, skb->data, h4 + 1, size - 1);
	/* Return it to the real stack after verifying the driver's copy. */
	skb_queue_tail(&m->hdev->rx_q, skb);
}

static void ws73_hci_acl_rx_test(struct kunit *test)
{
	struct ws73_hci_model *m = ws73_model_create(test, false);
	const u8 expected[] = { HCI_ACLDATA_PKT, 1, 0x20, 3, 0, 0xaa, 0xbb, 0xcc };
	u8 input[sizeof(expected)];
	unsigned int before;
	size_t split;

	KUNIT_ASSERT_NOT_NULL(test, m);
	/* Split every header/payload boundary; changing the source must be harmless. */
	for (split = 1; split < sizeof(input); split++) {
		disable_work_sync(&m->hdev->rx_work);
		before = m->hdev->stat.byte_rx;
		memcpy(input, expected, sizeof(input));
		ws73_ble_receive(m->adev, input, split);
		memset(input, 0xee, split);
		KUNIT_EXPECT_TRUE(test, skb_queue_empty(&m->hdev->rx_q));
		KUNIT_EXPECT_EQ(test, m->hdev->stat.byte_rx, before);
		ws73_ble_receive(m->adev, input + split, sizeof(input) - split);
		memset(input, 0xee, sizeof(input));
		KUNIT_EXPECT_EQ(test, skb_queue_len(&m->hdev->rx_q), 1);
		ws73_model_expect_rx(test, m, expected, sizeof(expected));
		enable_work(&m->hdev->rx_work);
		queue_work(m->hdev->workqueue, &m->hdev->rx_work);
		flush_work(&m->hdev->rx_work);
		KUNIT_EXPECT_EQ(test, m->hdev->stat.byte_rx, before + sizeof(input) - 1);
	}
	/* HCI_INIT intentionally drops ACL: no connection/L2CAP qualification. */
	ws73_ble_fault(m->adev, -ECANCELED);
	ws73_model_withdrawn(test, m);
}

static int ws73_model_flush_thread(void *context)
{
	struct ws73_hci_model *m = context;

	complete(&m->flushing);
	m->flush_result = m->hdev->flush(m->hdev);
	complete(&m->flushed);
	return 0;
}

static void ws73_hci_active_flush_test(struct kunit *test)
{
	struct ws73_hci_model *m = ws73_model_create(test, true);
	const u8 event[] = { HCI_EVENT_PKT, 0xff, 1, 0x73 };
	struct sk_buff *skb;
	unsigned long deadline;
	unsigned int before;
	bool waiting;
	int ret;

	KUNIT_ASSERT_NOT_NULL(test, m);
	skb = ws73_model_packet();
	KUNIT_ASSERT_NOT_NULL(test, skb);
	ret = m->hdev->send(m->hdev, skb);
	if (ret)
		kfree_skb(skb);
	KUNIT_ASSERT_EQ(test, ret, 0);
	m->flusher = kthread_create(ws73_model_flush_thread, m, "ws73-hci-flush");
	if (IS_ERR(m->flusher)) {
		m->flusher = NULL;
		KUNIT_FAIL(test, "cannot start flush thread");
		return;
	}
	get_task_struct(m->flusher);
	wake_up_process(m->flusher);
	KUNIT_ASSERT_TRUE(test, wait_for_completion_timeout(&m->flushing, HZ));
	/* The only blocking operation after that completion is the driver's flush.
	 * Observe its join wait before releasing the model's in-flight Reset.
	 */
	deadline = jiffies + HZ;
	do {
		waiting = READ_ONCE(m->flusher->__state) == TASK_UNINTERRUPTIBLE;
		if (waiting || completion_done(&m->flushed))
			break;
		usleep_range(1000, 2000);
	} while (time_before(jiffies, deadline));
	KUNIT_EXPECT_TRUE(test, waiting);
	KUNIT_EXPECT_FALSE(test, completion_done(&m->flushed));
	/* RX stays admitted while flush waits on TX, including native event delivery. */
	before = m->hdev->stat.byte_rx;
	ws73_ble_receive(m->adev, event, sizeof(event));
	flush_work(&m->hdev->rx_work);
	KUNIT_EXPECT_EQ(test, m->hdev->stat.byte_rx, before + sizeof(event) - 1);
	complete_all(&m->release);
	KUNIT_ASSERT_TRUE(test, wait_for_completion_timeout(&m->flushed, 5 * HZ));
	KUNIT_EXPECT_EQ(test, m->flush_result, -ECANCELED);
	ws73_model_withdrawn(test, m);
	KUNIT_EXPECT_EQ(test, m->acls, 0);
	KUNIT_EXPECT_EQ(test, ws73_ble_start(m->adev), -ECANCELED);
}

static void ws73_hci_rx_fault_test(struct kunit *test)
{
	struct ws73_hci_model *m = ws73_model_create(test, false);
	const u8 invalid[] = { HCI_ACLDATA_PKT, 1, 0, 0xff, 0xff };
	const u8 valid[] = { HCI_EVENT_PKT, 0xff, 1, 0x73 };
	struct sk_buff *skb;
	unsigned int before;

	KUNIT_ASSERT_NOT_NULL(test, m);
	skb = ws73_model_packet();
	KUNIT_ASSERT_NOT_NULL(test, skb);
	before = m->hdev->stat.byte_rx;
	ws73_ble_receive(m->adev, invalid, sizeof(invalid));
	/* Rejection is synchronous even before deferred HCI withdrawal runs. */
	KUNIT_EXPECT_EQ(test, m->hdev->send(m->hdev, skb), -EMSGSIZE);
	KUNIT_EXPECT_MEMEQ(test, skb->data, ws73_model_acl, sizeof(ws73_model_acl));
	kfree_skb(skb);
	ws73_ble_receive(m->adev, valid, sizeof(valid));
	ws73_model_withdrawn(test, m);
	KUNIT_EXPECT_EQ(test, m->hdev->stat.byte_rx, before);
	KUNIT_EXPECT_EQ(test, m->hdev->stat.err_rx, 1);
	KUNIT_EXPECT_EQ(test, m->acls, 0);
	KUNIT_EXPECT_EQ(test, ws73_ble_start(m->adev), -EMSGSIZE);
}

